#!/usr/bin/env bash
# Rebuild this fork's branded branch on top of upstream, without ever rebasing the
# brand commit. See FORK.org for why the brand is generated instead of replayed.
#
#   NousResearch/hermes-agent@main
#     -> ai/main            our real work (features, persona, fixes). Rebased by hand.
#     -> ai/slave-agent     ai/main + exactly ONE generated brand commit. Never edited.
#
# Usage:
#   scripts/fork-sync.sh            fetch upstream, rebase ai/main, regenerate brand
#   scripts/fork-sync.sh --no-fetch use the upstream ref already in the repo
#   scripts/fork-sync.sh --check    report how far behind upstream we are, change nothing
#
# Everything destructive here is limited to the generated branch, and only when it
# holds nothing but the brand commit (enforced below).
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$ROOT"

UPSTREAM_REMOTE=${UPSTREAM_REMOTE:-origin}     # points at the upstream project
BRANCH_BASE=${BRANCH_BASE:-ai/main}            # our work, rebased on upstream
BRANCH_BRAND=${BRANCH_BRAND:-ai/slave-agent}   # generated, disposable

MODE=sync
for arg in "$@"; do
  case "$arg" in
    --no-fetch) MODE=sync-nofetch ;;
    --check)    MODE=check ;;
    *) echo "unknown argument: $arg" >&2; exit 2 ;;
  esac
done

if [[ $MODE == check ]]; then
  behind=$(git rev-list --count "$BRANCH_BASE..$UPSTREAM_REMOTE/main" 2>/dev/null || echo "?")
  echo "upstream commits not yet in $BRANCH_BASE: $behind"
  git log --oneline -5 "$UPSTREAM_REMOTE/main" 2>/dev/null || true
  exit 0
fi

[[ $MODE == sync ]] && git fetch "$UPSTREAM_REMOTE" main

# The brand branch is derived. Refuse to throw it away if it carries anything that
# is not the brand commit -- that would be hand-written work, and it must live on
# $BRANCH_BASE instead.
if git rev-parse --verify -q "$BRANCH_BRAND" >/dev/null; then
  extra=$(git log --oneline "$BRANCH_BASE..$BRANCH_BRAND" | wc -l)
  if [[ $extra -gt 1 ]]; then
    echo "$BRANCH_BRAND has $extra commits on top of $BRANCH_BASE; expected 1 (the brand commit)." >&2
    echo "Move real work to $BRANCH_BASE first: git cherry-pick / git rebase --onto" >&2
    exit 1
  fi
fi

[[ -n $(git status --porcelain) ]] && { echo "working tree not clean; commit or stash first" >&2; exit 1; }

echo "== step 1/3: our work onto upstream/$(git rev-parse --short "$UPSTREAM_REMOTE/main")"
git checkout "$BRANCH_BASE"
git rebase "$UPSTREAM_REMOTE/main"
echo "   rebase clean. If it stopped, resolve as usual and re-run this script."

echo "== step 2/3: regenerate the brand from the merged tree"
git checkout -B "$BRANCH_BRAND" "$BRANCH_BASE"
python3 scripts/rebrand.py --apply     # both tiers + path renames + verify

echo "== step 3/3: one brand commit at the tip"
git add -A
git commit -q -m "brand: regenerate for upstream $(git rev-parse --short "$UPSTREAM_REMOTE/main")

Generated by scripts/rebrand.py on top of $BRANCH_BASE. Do not edit this commit
by hand and do not rebase it -- re-run scripts/fork-sync.sh instead. See FORK.org.

Co-Authored-By: OMP <omp@omp.sh>
Co-authored-by: Khalid Rafi <khaalidrafi@gmail.com>"
git log --oneline -3
